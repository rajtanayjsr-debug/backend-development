/**
 * Simple CMS - Pure MongoDB Implementation (Standard Exam Version)
 *
 * Requirements:
 * - Express.js + EJS + MongoDB Driver
 * - Connects to mongodb://127.0.0.1:27017
 * - Database: cms_lab, Collection: posts
 */

const express = require("express");
const path = require("path");
const { MongoClient, ObjectId } = require("mongodb");

const app = express();
const PORT = 3000;

// MongoDB Connection
const MONGO_URL = "mongodb://127.0.0.1:27017";
const client = new MongoClient(MONGO_URL);

let postsCollection;

async function connectDB() {
    try {
        await client.connect();
        const database = client.db("cms_lab");
        postsCollection = database.collection("posts");
        console.log("Connected to MongoDB at " + MONGO_URL);
    } catch (error) {
        console.error("Failed to connect to MongoDB:", error);
    }
}

connectDB();

// Express & View Engine setup
app.set("view engine", "ejs");
app.set("views", path.join(__dirname, "views"));
app.use(express.urlencoded({ extended: true }));
app.use(express.static(path.join(__dirname, "public")));

// Date and exact time formatting helper for EJS
app.locals.formatDate = function (dateInput) {
    if (!dateInput) return "";
    const date = new Date(dateInput);
    if (isNaN(date.getTime())) return "";

    const datePart = date.toLocaleDateString("en-GB", {
        day: "numeric",
        month: "long",
        year: "numeric"
    });
    const timePart = date.toLocaleTimeString("en-US", {
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
        hour12: true
    });

    return `${datePart} at ${timePart}`;
};
app.locals.formatDateTime = app.locals.formatDate;


// Routes

// Root redirect
app.get("/", (req, res) => {
    res.redirect("/posts");
});

// 1. Display All Posts (Post List)
app.get("/posts", async (req, res) => {
    try {
        const posts = await postsCollection
            .find({}, { projection: { content: 0 } })
            .sort({ createdAt: -1 })
            .toArray();

        res.render("posts", { posts, pageTitle: "All Posts" });
    } catch (err) {
        console.error(err);
        res.status(500).send("Database query error");
    }
});

// 2. Display Create Post Form
app.get("/posts/new", (req, res) => {
    res.render("new-post", {
        errorMessage: null,
        formData: { title: "", content: "", author: "" },
        pageTitle: "Create New Post"
    });
});

// 3. Handle Create Post Form Submission
app.post("/posts", async (req, res) => {
    const { title, content, author } = req.body;

    // Validate inputs
    if (!title?.trim() || !content?.trim() || !author?.trim()) {
        return res.status(400).render("new-post", {
            errorMessage: "All fields are required.",
            formData: { title: title || "", content: content || "", author: author || "" },
            pageTitle: "Create New Post"
        });
    }

    try {
        await postsCollection.insertOne({
            title: title.trim(),
            content: content.trim(),
            author: author.trim(),
            createdAt: new Date() // Automatically generated by backend
        });

        res.redirect("/posts");
    } catch (err) {
        console.error(err);
        res.status(500).send("Failed to save post");
    }
});

// 4. View Individual Post
app.get("/posts/:id", async (req, res) => {
    try {
        if (!ObjectId.isValid(req.params.id)) {
            return res.status(404).render("post", {
                post: null,
                errorMessage: "Invalid post ID.",
                pageTitle: "Post Not Found"
            });
        }

        const post = await postsCollection.findOne({
            _id: new ObjectId(req.params.id)
        });

        if (!post) {
            return res.status(404).render("post", {
                post: null,
                errorMessage: "Post not found.",
                pageTitle: "Post Not Found"
            });
        }

        res.render("post", {
            post,
            errorMessage: null,
            pageTitle: post.title
        });
    } catch (err) {
        console.error(err);
        res.status(500).send("Failed to retrieve post");
    }
});

app.listen(PORT, () => {
    console.log(`Server is running at http://localhost:${PORT}`);
});
